#!/usr/bin/env python3
"""Generate site/src/content/docs/start/cli.md from the live toolbox CLI.

Source of truth:
  - `toolbox describe` NDJSON (command tree + MCP ↔ CLI map)
  - `toolbox <command…> --help` (flags and usage text)

Usage (from repo root):
  python3 scripts/generate-cli-docs.py
  python3 scripts/generate-cli-docs.py --check   # exit 1 if committed page is stale
  TOOLBOX_BIN=./target/debug/toolbox python3 scripts/generate-cli-docs.py

Copy this file to scripts/generate-cli-docs.py in the toolbox repo.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT_PATH = REPO_ROOT / "site" / "src" / "content" / "docs" / "start" / "cli.md"
MARKER = "<!-- GENERATED by scripts/generate-cli-docs.py — do not edit by hand -->"


def resolve_toolbox() -> str:
    env = os.environ.get("TOOLBOX_BIN")
    if env:
        return env
    candidates = [
        REPO_ROOT / "target" / "debug" / "toolbox",
        REPO_ROOT / "target" / "release" / "toolbox",
        shutil.which("toolbox"),
    ]
    for c in candidates:
        if c and Path(c).exists():
            return str(c)
    # Build debug binary if missing
    subprocess.check_call(
        ["cargo", "build", "-p", "toolbox-cli", "--locked"],
        cwd=REPO_ROOT,
    )
    bin_path = REPO_ROOT / "target" / "debug" / "toolbox"
    if not bin_path.exists():
        sys.exit("toolbox binary not found after build")
    return str(bin_path)


def run_json_lines(toolbox: str, *args: str) -> list[dict]:
    proc = subprocess.run(
        [toolbox, *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    out = []
    for line in proc.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        out.append(json.loads(line))
    return out


def help_text(toolbox: str, argv: list[str]) -> str:
    proc = subprocess.run(
        [toolbox, *argv, "--help"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    text = (proc.stdout or proc.stderr or "").rstrip()
    return text


def section_anchor(name: str) -> str:
    return name.replace(" ", "-")


def render(commands: list[dict], mcp_tools: list[dict], helps: dict[str, str]) -> str:
    lines: list[str] = []
    lines.append("---")
    lines.append("title: CLI reference")
    lines.append(
        "description: Primary toolbox commands and the MCP tools that share the same authorization path."
    )
    lines.append("sidebar:")
    lines.append("  order: 4")
    lines.append("draft: false")
    lines.append("---")
    lines.append("")
    lines.append(MARKER)
    lines.append("")
    lines.append(
        "The `toolbox` binary is the operator and user surface. Catalog **reads** are the same over the CLI, MCP, and HTTP: one authorization path, one snapshot model."
    )
    lines.append("")
    lines.append(
        "This page is **generated from the CLI** (`toolbox describe` plus each command’s `--help`). Do not edit it by hand — run `python3 scripts/generate-cli-docs.py` (or `npm run generate:cli-docs` from `site/`). Use `--check` in CI to fail when the committed page is stale."
    )
    lines.append("")
    lines.append(
        "Install: [Quickstart](/toolbox/start/quickstart/) or [Install a release](/toolbox/start/install/)."
    )
    lines.append("")

    # Overview table from describe
    lines.append("## Commands")
    lines.append("")
    lines.append("| Command | About | MCP tool |")
    lines.append("|---|---|---|")
    for cmd in commands:
        data = cmd["data"]
        name = data["name"]
        about = (data.get("about") or "").replace("|", "\\|").replace("\n", " ")
        mcp = data.get("mcpTool") or "—"
        lines.append(f"| [`toolbox {name}`](#{section_anchor(name)}) | {about} | `{mcp}` |" if mcp != "—" else f"| [`toolbox {name}`](#{section_anchor(name)}) | {about} | — |")
    lines.append("")

    # MCP map
    lines.append("## MCP tools")
    lines.append("")
    lines.append(
        "Built-in MCP tools and the CLI commands that share the same path. Agent loop: [Read the catalog from an agent](/toolbox/agents/reads/)."
    )
    lines.append("")
    lines.append("| MCP tool | CLI |")
    lines.append("|---|---|")
    for tool in mcp_tools:
        data = tool["data"]
        name = data["name"]
        clis = data.get("cliCommands") or []
        cli_cell = ", ".join(f"`{c}`" for c in clis) if clis else "—"
        lines.append(f"| `{name}` | {cli_cell} |")
    lines.append("")
    lines.append("```bash")
    lines.append("toolbox mcp --url http://127.0.0.1:8080")
    lines.append("# or attach an MCP client to http://127.0.0.1:8080/mcp on a running serve")
    lines.append("```")
    lines.append("")

    # Per-command help
    lines.append("## Command help")
    lines.append("")
    lines.append("Help text below is taken verbatim from `toolbox <command> --help`.")
    lines.append("")
    for cmd in commands:
        name = cmd["data"]["name"]
        lines.append(f"### `{name}`")
        lines.append("")
        lines.append("```text")
        lines.append(helps.get(name, "(help unavailable)").rstrip())
        lines.append("```")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def generate(toolbox: str) -> str:
    records = run_json_lines(toolbox, "describe")
    commands = [r for r in records if r.get("kind") == "command"]
    mcp_tools = [r for r in records if r.get("kind") == "mcp-tool"]
    commands.sort(key=lambda r: r["data"]["name"])
    mcp_tools.sort(key=lambda r: r["data"]["name"])

    helps: dict[str, str] = {}
    for cmd in commands:
        name = cmd["data"]["name"]
        argv = name.split()
        helps[name] = help_text(toolbox, argv)
    return render(commands, mcp_tools, helps)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if committed cli.md differs from a fresh generation",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=OUT_PATH,
        help="Output path (default: site/src/content/docs/start/cli.md)",
    )
    args = parser.parse_args()
    toolbox = resolve_toolbox()
    body = generate(toolbox)

    if args.check:
        if not args.out.exists():
            print(f"missing {args.out}", file=sys.stderr)
            return 1
        current = args.out.read_text()
        if current != body:
            print(
                f"{args.out} is stale. Run: python3 scripts/generate-cli-docs.py",
                file=sys.stderr,
            )
            return 1
        print(f"{args.out} is up to date")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(body)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    # When copied to scripts/, REPO_ROOT is parents[1]. When run from the store
    # copy for preview, allow TOOLBOX_REPO override.
    if os.environ.get("TOOLBOX_REPO"):
        REPO_ROOT = Path(os.environ["TOOLBOX_REPO"]).resolve()
        OUT_PATH = REPO_ROOT / "site" / "src" / "content" / "docs" / "start" / "cli.md"
    raise SystemExit(main())
