// Assemble the Astro build into the offline HTML template embedded by the Seikika CLI.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const dist = new URL("../dist/", import.meta.url);
const target = new URL("../../crates/seikika-cli/report-dist/", import.meta.url);
const html = await readFile(new URL("index.html", dist), "utf8");

const entry = /<script type="module" src="([^"]+)"><\/script>/g;
const data = /(<script\b(?=[^>]*\bid="seikika-report-data")[^>]*>).*?(<\/script>)/s;
const scripts = [...html.matchAll(entry)];
if (scripts.length !== 1 || !data.test(html)) throw new Error("Report requires one bundled script and one snapshot element");
const input = fileURLToPath(new URL(scripts[0][1].replace(/^\//, ""), dist));
const result = await build({
  configFile: false,
  logLevel: "warn",
  build: {
    write: false,
    modulePreload: false,
    rolldownOptions: { input, output: { format: "iife", codeSplitting: false } },
  },
});
const chunks = (Array.isArray(result) ? result : [result]).flatMap(build => build.output);
if (chunks.length !== 1 || chunks[0].type !== "chunk") {
  throw new Error("The offline report must bundle all of its JavaScript");
}
const client = chunks[0].code.replace(/<\/script/gi, match => "<\\/" + match.slice(2));
const sheets = /<link rel="stylesheet" href="([^"]+)">/g;
let template = html.replace(/<title>[^<]*<\/title>/, '<title>Seikika report</title>').replace(entry, '<script type="module">/*CLIENT*/</script>').replace(data, "$1/*DATA*/$2");
for (const match of html.matchAll(sheets)) {
  const css = await readFile(new URL(match[1].replace(/^\//, ""), dist), "utf8");
  template = template.replace(match[0], () => "<style>" + css + "</style>");
}

await mkdir(target, { recursive: true });
await writeFile(new URL("report.html", target), template.trimEnd() + "\n");
await writeFile(new URL("seikika-report.js", target), "// Generated by pnpm build from the Astro report.\n" + client);
