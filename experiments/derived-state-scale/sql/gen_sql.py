"""Generates pipeline.sql: the same derivation pipeline as src/main.rs, as plain Postgres views and
materialised views. The 100 rules are the same 10 templates x k as the CEL rules, translated to SQL."""
T = [
    "(owner <> -1 AND tier <= {k})",
    "(runbook OR tier > {k})",
    "(lang IN ('go','rust','python') AND coverage >= {k})",
    "(vulns = 0 OR tier > {k4})",
    "(CASE WHEN pci THEN coverage > {k} ELSE true END)",
    "(length(description) > {k} AND on_call <> '')",
    "(NOT ('legacy-{k}' = ANY(deps)))",
    "(image_age < 30 + {k})",
    "(slo AND alerts >= {k5})",
    "(name LIKE 'svc%' OR coverage > {k90})",
]
rules = [T[i % 10].format(k=i % 97, k4=(i % 97) % 4, k5=(i % 97) % 5, k90=(i % 97) % 90) for i in range(100)]
passed = " +\n    ".join(f"{r}::int" for r in rules)
level = "CASE WHEN p >= 90 THEN 3 WHEN p >= 75 THEN 2 WHEN p >= 60 THEN 1 ELSE 0 END"
sql = f"""-- generated by gen_sql.py; do not edit
DROP VIEW IF EXISTS entities, entity_scores CASCADE;
-- merge by per-field precedence: git > connector
CREATE VIEW entities AS
  SELECT g.id, g.name, COALESCE(g.owner_team, c.owner_team, -1) AS owner, COALESCE(g.tier, c.tier) AS tier,
         g.lang, g.description, g.pci, g.runbook, g.system, g.deps, COALESCE(c.on_call, '') AS on_call,
         c.coverage, c.vulns, c.image_age, c.slo, c.alerts
  FROM git_frag g JOIN conn_frag c USING (id);
-- 100 rules, computed on read (plain view)
CREATE VIEW entity_scores AS
  SELECT id, owner, system, p AS passed, {level} AS level
  FROM (SELECT id, owner, system,
    {passed} AS p
  FROM entities) x;
CREATE MATERIALIZED VIEW mv_scores AS SELECT * FROM entity_scores WITH NO DATA;
CREATE MATERIALIZED VIEW mv_indeg AS SELECT dst AS id, count(*) AS dependents FROM edges GROUP BY dst WITH NO DATA;
CREATE MATERIALIZED VIEW mv_depmin AS
  SELECT e.src AS id, min(s.level) AS min_dep_level FROM edges e JOIN mv_scores s ON s.id = e.dst GROUP BY e.src WITH NO DATA;
CREATE MATERIALIZED VIEW mv_team_anc AS
  WITH RECURSIVE a(team, ancestor) AS (SELECT id, id FROM teams
    UNION ALL SELECT a.team, t.parent FROM a JOIN teams t ON t.id = a.ancestor WHERE t.parent IS NOT NULL)
  SELECT * FROM a WITH NO DATA;
CREATE MATERIALIZED VIEW mv_team_rollup AS
  SELECT a.ancestor AS team, count(*) AS services, sum(s.passed) AS passed
  FROM mv_scores s JOIN mv_team_anc a ON a.team = s.owner GROUP BY a.ancestor WITH NO DATA;
CREATE MATERIALIZED VIEW mv_domain_rollup AS
  SELECT sy.domain, count(*) AS services, sum(s.passed) AS passed
  FROM mv_scores s JOIN systems sy ON sy.id = s.system GROUP BY sy.domain WITH NO DATA;
CREATE MATERIALIZED VIEW mv_tuples AS
  SELECT 'service:' || id AS object, 'owner' AS relation, 'team:' || owner AS subject FROM mv_scores WHERE owner >= 0
  UNION ALL SELECT 'service:' || id, 'parent', 'system:' || system FROM mv_scores
  UNION ALL SELECT 'system:' || id, 'parent', 'domain:' || domain FROM systems
  UNION ALL SELECT 'team:' || id, 'parent', 'team:' || parent FROM teams WHERE parent IS NOT NULL
  UNION ALL SELECT 'team:' || team, 'member', 'user:' || user_id FROM members
  WITH NO DATA;
-- ListObjects for every user, materialised: member of owner team or any ancestor team
CREATE MATERIALIZED VIEW mv_perm AS
  SELECT DISTINCT m.user_id, s.id AS service
  FROM members m JOIN mv_team_anc a ON a.ancestor = m.team JOIN mv_scores s ON s.owner = a.team WITH NO DATA;
"""
open("pipeline.sql", "w").write(sql)
