// The Rust release embeds the complete Astro output and needs no JavaScript tooling at runtime.
import { readdir, readFile, writeFile } from "node:fs/promises";

const dist = new URL("../dist/", import.meta.url);
const files = await readdir(new URL("assets/", dist));
const types = { ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8" };
const manifest = files.sort().map(file => {
  const type = types[file.slice(file.lastIndexOf("."))];
  if (!type || !/^[A-Za-z0-9_.-]+$/.test(file)) throw new Error("Unexpected Astro asset " + file);
  return `    ("/assets/${file}", "${type}", include_str!("assets/${file}")),`;
});
const html = await readFile(new URL("index.html", dist), "utf8");
if (!html.includes('<!-- seikika:entity -->') || !/<script type="module" src="\/assets\//.test(html)) {
  throw new Error("The server requires an entity placeholder and an external Astro client script");
}
await writeFile(new URL("assets.rs", dist),
  "// Generated by pnpm build.\nconst ASSETS: &[(&str, &str, &str)] = &[\n" + manifest.join("\n") + "\n];\n");
